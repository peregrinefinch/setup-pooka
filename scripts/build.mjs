import { build } from 'esbuild';
import { mkdir, copyFile } from 'node:fs/promises';

await mkdir('dist', { recursive: true });
await build({
  entryPoints: ['index.mjs'], outfile: 'dist/index.mjs', bundle: true,
  platform: 'node', target: 'node24', format: 'esm', legalComments: 'inline',
  banner: { js: "// SPDX-License-Identifier: Apache-2.0\n// Generated by npm run build. SemVer licence: LICENSE.semver.\nimport { createRequire } from 'node:module'; const require = createRequire(import.meta.url);" },
});
await copyFile('node_modules/semver/LICENSE', 'dist/LICENSE.semver');
